"""
Generate the Rust structs holding GSFit's settings, and the code reading their XML into them, from the XML schemas in `python/gsfit/settings_schema/xsd/`.

Writes `settings_<ids>.rs`, in `rust/gsfit_rs/src/settings/`, for each IDS GSFit builds, from `<ids>/<ids>.xsd`, in `xsd/` next to this script, and the XML schemas
of the files it links to.
`workflow.xsd`, which the settings of every IDS read from MDSplus link to, is generated into a module of its own, `settings_workflow.rs`, so that they all read
their link into the same struct, `SettingsWorkflow`.
The XML schema is the source of truth, so re-run this after changing it.

The structs and readers are generated by `generate_rust_structs`, which says how each XML schema is translated; this script gives it GSFit's paths and names.

Usage:
    python python/gsfit/settings_schema/_generate_rust_schema.py
"""

from pathlib import Path

from diagnostic_and_simulation_base.xml_reader_and_writer import SharedModule
from diagnostic_and_simulation_base.xml_reader_and_writer import generate_rust_structs

if __name__ == "__main__":
    # This script sits in `python/gsfit/settings_schema/`, three levels below the repository root, next to the XML schemas, in `xsd/`
    generator_path: Path = Path(__file__).resolve()
    repository_path: Path = generator_path.parents[3]

    # `workflow.xsd`, which the settings of several IDSs link to, in a module of its own
    workflow_module: SharedModule = SharedModule(
        xsd_path=generator_path.parent / "xsd" / "workflow.xsd",
        rust_module="crate::settings::settings_workflow",
        root_struct_name="SettingsWorkflow",
    )
    generate_rust_structs(
        xsd_path=workflow_module.xsd_path,
        output_path=repository_path / "rust" / "gsfit_rs" / "src" / "settings" / "settings_workflow.rs",
        root_struct_name=workflow_module.root_struct_name,
        named_type_struct_prefix="Settings",
        shared_modules=[workflow_module],
        title="The MDSplus trees which the database reader reads from, and which run of each, read from their XML into structs",
        leaf_readers_module="crate::settings::settings_leaf_readers",
        rustfmt_config_path=repository_path / "rust" / "rustfmt.toml",
        rust_edition="2024",
        generator_path=generator_path,
        repository_path=repository_path,
    )

    # The IDS, the struct of its settings' root element, and what the settings are for
    settings_to_generate: list[tuple[str, str, str]] = [
        ("core_profiles", "SettingsCoreProfiles", "The settings the kinetic profiles are built with"),
        ("core_sources", "SettingsCoreSources", "The settings the sources of the plasma are built with"),
        ("equilibrium", "SettingsEquilibrium", "The settings the equilibrium is reconstructed with"),
        ("magnetics", "SettingsMagnetics", "The settings the magnetic sensors are built with"),
        ("pf_active", "SettingsPfActive", "The settings the PF coils are built with"),
        ("pf_passive", "SettingsPfPassive", "The settings the passive conductors are built with"),
        ("pulse_schedule", "SettingsPulseSchedule", "The settings the pulse schedule is built with"),
        ("tf", "SettingsTf", "The settings the toroidal field is built with"),
        ("wall", "SettingsWall", "The settings the wall is built with"),
    ]
    for ids_name, root_struct_name, purpose in settings_to_generate:
        generate_rust_structs(
            xsd_path=generator_path.parent / "xsd" / ids_name / f"{ids_name}.xsd",
            output_path=repository_path / "rust" / "gsfit_rs" / "src" / "settings" / f"settings_{ids_name}.rs",
            root_struct_name=root_struct_name,
            named_type_struct_prefix=root_struct_name,
            shared_modules=[workflow_module],
            title=f"{purpose}, read from their XML into structs",
            leaf_readers_module="crate::settings::settings_leaf_readers",
            rustfmt_config_path=repository_path / "rust" / "rustfmt.toml",
            rust_edition="2024",
            generator_path=generator_path,
            repository_path=repository_path,
        )
