"""
Generate the Python types in `python/gsfit/settings_schema/python/` from the XML schemas in `python/gsfit/settings_schema/xsd/`.

The types are generated by `generate_python_dataclasses`, which says how each XML schema is translated; this script gives it GSFit's directories and title.

Usage:
    python python/gsfit/settings_schema/_generate_python_schema.py
"""

from pathlib import Path

from diagnostic_and_simulation_base.xml_reader_and_writer import generate_python_dataclasses

if __name__ == "__main__":
    # This script sits in `python/gsfit/settings_schema/`, three levels below the repository root,
    # next to the XML schemas, in `xsd/`, and the generated modules, in `python/`
    generator_path: Path = Path(__file__).resolve()
    generate_python_dataclasses(
        xsd_directory_path=generator_path.parent / "xsd",
        output_directory_path=generator_path.parent / "python",
        title="GSFit settings types",
        generator_path=generator_path,
        repository_path=generator_path.parents[3],
    )
