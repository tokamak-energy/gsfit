"""
Generate the Rust structs holding the Guazzotto-Freidberg analytic solution's settings, and the code reading their XML into them, from their XML schemas.

Writes `rust/gsfit_rs/src/analytic_grad_shafranov/guazzotto_freidberg/settings_schema.rs`, from `xsd/equilibrium/equilibrium.xsd`, next to this script,
and the XML schemas of the files it links to.

The structs and readers are generated by `generate_rust_structs`, which says how each XML schema is translated; this script gives it the Guazzotto-Freidberg
analytic solution's paths and names.

Usage:
    python python/analytic_grad_shafranov/guazzotto_freidberg/settings_schema/_generate_rust_schema.py
"""

from pathlib import Path

from diagnostic_and_simulation_base.xml_reader_and_writer import generate_rust_structs

if __name__ == "__main__":
    # This script sits in `python/analytic_grad_shafranov/guazzotto_freidberg/settings_schema/`, four levels below the repository root,
    # next to the XML schemas, in `xsd/`
    generator_path: Path = Path(__file__).resolve()
    repository_path: Path = generator_path.parents[4]
    generate_rust_structs(
        xsd_path=generator_path.parent / "xsd" / "equilibrium" / "equilibrium.xsd",
        output_path=repository_path / "rust" / "gsfit_rs" / "src" / "analytic_grad_shafranov" / "guazzotto_freidberg" / "settings_schema.rs",
        root_struct_name="GuazzottoFreidbergSettings",
        named_type_struct_prefix="GuazzottoFreidbergSettings",
        shared_modules=[],
        title="The Guazzotto-Freidberg analytic solution's settings, read from the XML of `equilibrium/code/parameters` into structs",
        leaf_readers_module="crate::settings::settings_leaf_readers",
        rustfmt_config_path=repository_path / "rust" / "rustfmt.toml",
        rust_edition="2024",
        generator_path=generator_path,
        repository_path=repository_path,
    )
