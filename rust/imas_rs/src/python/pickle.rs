//! Pickling: converting an IDS, or any structure generated as one is, to and from the Python objects which `pickle` stores.
//!
//! The state of a structure is a `dict` of its nodes, keyed by their names in the data dictionary, e.g. `loop`, not Rust's
//! `r#loop`. An array of structures is a `list` holding every element, and a leaf is the Python value it holds: a `float`,
//! `int`, `complex` or `str`, a `list` of `str`, or a NumPy array. A node holding its IMAS "unset" value (see
//! `dd_base_types.rs`) is left out, and is unset again when the state is read back, so the state holds only what has been set.
//! A structure all of whose nodes are unset is left out too.
//!
//! The implementations for the leaves and for `Vec` are here. Those for the structs are generated by `imas_updater/build_ids.py`,
//! one file for each IDS, `<ids>_pickle.rs`. A class holding a structure pickles it through `__reduce__`, as `PyEquilibrium`
//! does, because Python cannot construct the class: the state is read back by its static method `_from_pickle_state`.

use crate::dd_base_types::EMPTY_INT;
use ndarray::{Array, Dimension};
use num_complex::Complex64;
use numpy::{Element, PyArray, PyArrayDescr, PyArrayMethods, PyUntypedArray, PyUntypedArrayMethods, ToPyArray};
use pyo3::exceptions::PyValueError;
use pyo3::prelude::*;
use pyo3::types::{PyComplex, PyDict, PyFloat, PyInt, PyList, PyString};

/// A structure, or a node of one, which can be pickled: converted to and from the Python object which `pickle` stores.
pub trait PickleState: Sized {
    /// Whether this holds its IMAS "unset" value, in which case it is left out of the state of the structure holding it
    fn is_unset(&self) -> bool;

    /// The Python object holding this, which `pickle` stores
    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>>;

    /// Read this back from the Python object which `to_pickle_state` made.
    ///
    /// # Errors
    /// When `state` is not what `to_pickle_state` makes, e.g. it was pickled with a different version of the data dictionary
    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError>;
}

/// Why a state could not be read back, and where.
///
/// It is made where the state is wrong. Each structure it passes through on its way out puts the node it was reading in front of
/// `path`, which so ends up as the node's whole path, as `Path` prints it, e.g. `time_slice(3)/profiles_2d(0)/psi`.
#[derive(Debug)]
pub struct PickleStateError {
    /// The path of the node whose state is wrong, from the structure being read back; empty when it is that structure's own state
    path: String,
    /// What is wrong with the state, e.g. "should be a `float`, but is a `str`"
    reason: String,
}

impl PickleStateError {
    /// A state which is not of the Python type its node is pickled as, e.g. a `str` for a `float`.
    ///
    /// # Arguments
    /// * `expected` - what the state should be, e.g. "a `float`"
    /// * `state` - the state which was found instead
    pub fn wrong_type(expected: &str, state: &Bound<'_, PyAny>) -> Self {
        let found: String = match state.cast::<PyUntypedArray>() {
            Ok(array) => format!("a {}D NumPy array of `{}`", array.ndim(), array.dtype()),
            Err(_) => match state.get_type().name() {
                Ok(type_name) => format!("a `{type_name}`"),
                Err(_) => "of an unknown type".to_string(),
            },
        };
        Self {
            path: String::new(),
            reason: format!("should be {expected}, but is {found}"),
        }
    }

    /// A name in the state of a structure which is not one of its nodes
    pub fn unknown_node(name: &str) -> Self {
        Self {
            path: name.to_string(),
            reason: "is not a node".to_string(),
        }
    }

    /// Put `name`, the node whose state was being read back, in front of the path
    pub fn in_node(mut self, name: &str) -> Self {
        // An element's index joins its array's name, e.g. `profiles_2d` and `(0)/psi` make `profiles_2d(0)/psi`
        self.path = if self.path.is_empty() {
            name.to_string()
        } else if self.path.starts_with('(') {
            format!("{name}{}", self.path)
        } else {
            format!("{name}/{}", self.path)
        };
        self
    }

    /// Put `(i_element)`, the element of an array whose state was being read back, in front of the path
    pub fn in_element(mut self, i_element: usize) -> Self {
        self.path = if self.path.is_empty() {
            format!("({i_element})")
        } else {
            format!("({i_element})/{}", self.path)
        };
        self
    }

    /// The Python exception, a `ValueError`, for reading back the state of `what`, e.g. "the `equilibrium` IDS"
    pub fn into_py_err(self, what: &str) -> PyErr {
        if self.path.is_empty() {
            PyValueError::new_err(format!("The pickled state of {what} cannot be read back: it {}", self.reason))
        } else {
            PyValueError::new_err(format!("The pickled state of {what} cannot be read back: `{}` {}", self.path, self.reason))
        }
    }
}

/// The nodes in the state of a structure, which is a `dict` of them keyed by their names, as (name, state) pairs, in its order.
///
/// # Errors
/// When the state is not a `dict`, or one of its keys is not a `str`
pub fn structure_nodes<'py>(state: &Bound<'py, PyAny>) -> Result<Vec<(String, Bound<'py, PyAny>)>, PickleStateError> {
    let dictionary: &Bound<'py, PyDict> = state.cast::<PyDict>().map_err(|_| PickleStateError::wrong_type("a `dict`", state))?;
    let mut nodes: Vec<(String, Bound<'py, PyAny>)> = Vec::with_capacity(dictionary.len());
    for (key, node_state) in dictionary.iter() {
        let name: String = key.extract::<String>().map_err(|_| PickleStateError {
            path: String::new(),
            reason: format!("has a key which is not a `str`, `{key}`"),
        })?;
        nodes.push((name, node_state));
    }
    Ok(nodes)
}

/// `FLT_0D`, a `float`, which is unset when NaN
impl PickleState for f64 {
    fn is_unset(&self) -> bool {
        self.is_nan()
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        Ok(PyFloat::new(py, *self).into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        match state.cast::<PyFloat>() {
            Ok(float) => Ok(float.value()),
            Err(_) => Err(PickleStateError::wrong_type("a `float`", state)),
        }
    }
}

/// `INT_0D`, an `int`, which is unset when `EMPTY_INT`
impl PickleState for i32 {
    fn is_unset(&self) -> bool {
        *self == EMPTY_INT
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        Ok((*self).into_pyobject(py)?.into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        match state.cast::<PyInt>() {
            Ok(integer) => integer.extract::<i32>().map_err(|_| PickleStateError {
                path: String::new(),
                reason: format!("should be a 32-bit integer, but is {integer}"),
            }),
            Err(_) => Err(PickleStateError::wrong_type("an `int`", state)),
        }
    }
}

/// `STR_0D`, a `str`, which is unset when empty
impl PickleState for String {
    fn is_unset(&self) -> bool {
        self.is_empty()
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        Ok(PyString::new(py, self).into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        state.extract::<String>().map_err(|_| PickleStateError::wrong_type("a `str`", state))
    }
}

/// `CPX_0D`, a `complex`, which is unset when both its parts are NaN
impl PickleState for Complex64 {
    fn is_unset(&self) -> bool {
        self.re.is_nan() && self.im.is_nan()
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        Ok(PyComplex::from_doubles(py, self.re, self.im).into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        match state.cast::<PyComplex>() {
            Ok(complex) => Ok(Complex64::new(complex.real(), complex.imag())),
            Err(_) => Err(PickleStateError::wrong_type("a `complex`", state)),
        }
    }
}

/// The arrays, e.g. `FLT_2D` or `INT_1D`: a NumPy array of the same element type and number of dimensions, which is unset when
/// it is empty in every dimension, as `Default::default()` makes it. An array empty in only some of its dimensions is set, so that
/// its shape is kept
impl<A: Element, D: Dimension> PickleState for Array<A, D> {
    fn is_unset(&self) -> bool {
        let shape: &[usize] = self.shape();
        let n_dimension: usize = shape.len();
        for i_dimension in 0..n_dimension {
            if shape[i_dimension] != 0 {
                return false;
            }
        }
        true
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        Ok(self.to_pyarray(py).into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        match state.cast::<PyArray<A, D>>() {
            Ok(array) => Ok(array.to_owned_array()),
            Err(_) => {
                let dtype: Bound<'_, PyArrayDescr> = numpy::dtype::<A>(state.py());
                let expected: String = match D::NDIM {
                    Some(n_dimension) => format!("a {n_dimension}D NumPy array of `{dtype}`"),
                    None => format!("a NumPy array of `{dtype}`"),
                };
                Err(PickleStateError::wrong_type(&expected, state))
            }
        }
    }
}

/// `STR_1D`, a `list` of `str`, and an array of structures, a `list` of its elements' states, which are unset when empty. Every
/// element is in the `list`, unset or not, so that each keeps its index
impl<T: PickleState> PickleState for Vec<T> {
    fn is_unset(&self) -> bool {
        self.is_empty()
    }

    fn to_pickle_state<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py, PyAny>> {
        let state: Bound<'py, PyList> = PyList::empty(py);
        let n_element: usize = self.len();
        for i_element in 0..n_element {
            state.append(self[i_element].to_pickle_state(py)?)?;
        }
        Ok(state.into_any())
    }

    fn from_pickle_state(state: &Bound<'_, PyAny>) -> Result<Self, PickleStateError> {
        let list: &Bound<'_, PyList> = state.cast::<PyList>().map_err(|_| PickleStateError::wrong_type("a `list`", state))?;
        let n_element: usize = list.len();
        let mut elements: Vec<T> = Vec::with_capacity(n_element);
        for i_element in 0..n_element {
            let element_state: Bound<'_, PyAny> = list.get_item(i_element).map_err(|error: PyErr| {
                PickleStateError {
                    path: String::new(),
                    reason: format!("cannot be read: {error}"),
                }
                .in_element(i_element)
            })?;
            let element: T = T::from_pickle_state(&element_state).map_err(|error: PickleStateError| error.in_element(i_element))?;
            elements.push(element);
        }
        Ok(elements)
    }
}
